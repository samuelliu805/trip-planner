import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";

import { bentoPublicTemplateSourceV1 } from "../src/features/sharing/templates/builtins/bento/source.ts";
import { bentoPublicTemplateSourceV2 } from "../src/features/sharing/templates/builtins/bento/v2.ts";
import { etherealPublicTemplateSourceV1 } from "../src/features/sharing/templates/builtins/ethereal/source.ts";
import { journalPublicTemplateSourceV1 } from "../src/features/sharing/templates/builtins/journal/source.ts";
import { standardPublicTemplateSourceV1 } from "../src/features/sharing/templates/builtins/standard/source.ts";
import { traversePublicTemplateSourceV1 } from "../src/features/sharing/templates/builtins/traverse/source.ts";
import {
  compilePublicTemplate,
  stablePublicTemplateJson,
} from "../src/features/sharing/templates/compiler/index.ts";

const scriptsDirectory = dirname(fileURLToPath(import.meta.url));
const projectDirectory = resolve(scriptsDirectory, "..");
const prettierConfig = (await resolveConfig(resolve(projectDirectory, "package.json"))) ?? {};

const publicTemplateSources = [
  standardPublicTemplateSourceV1,
  bentoPublicTemplateSourceV1,
  bentoPublicTemplateSourceV2,
  etherealPublicTemplateSourceV1,
  journalPublicTemplateSourceV1,
  traversePublicTemplateSourceV1,
];

function generatedName(template) {
  return `${template.id}PublicTemplateV${template.version}`;
}

function generatedPublicTemplateSource(template) {
  const source = `// Generated by scripts/build-public-templates.mjs. Do not edit manually.\nimport type { CompiledPublicTemplateV1 } from "../schema.ts";\n\nexport const ${generatedName(template)} = ${JSON.stringify(template, null, 2)} as const satisfies CompiledPublicTemplateV1;\n`;
  return format(source, {
    ...prettierConfig,
    filepath: generatedPublicTemplatePath(template),
  });
}

function compilePublicTemplateSources() {
  return publicTemplateSources.map((source) => {
    const first = compilePublicTemplate(source);
    const second = compilePublicTemplate(source);
    if (stablePublicTemplateJson(first) !== stablePublicTemplateJson(second))
      throw new Error(`NON_DETERMINISTIC_TEMPLATE:${first.key}`);
    return first;
  });
}

function generatedPublicTemplatePath(template) {
  return resolve(
    projectDirectory,
    "src/features/sharing/templates/generated",
    `${template.id}-v${template.version}.ts`,
  );
}

export async function writeCompiledPublicTemplates() {
  const templates = compilePublicTemplateSources();
  await mkdir(resolve(projectDirectory, "src/features/sharing/templates/generated"), {
    recursive: true,
  });
  await Promise.all(
    templates.map(async (template) =>
      writeFile(
        generatedPublicTemplatePath(template),
        await generatedPublicTemplateSource(template),
      ),
    ),
  );
  return templates;
}

export async function validateCompiledPublicTemplates() {
  const templates = compilePublicTemplateSources();
  for (const template of templates) {
    const expected = await generatedPublicTemplateSource(template);
    const actual = await readFile(generatedPublicTemplatePath(template), "utf8");
    if (actual !== expected) throw new Error(`STALE_PUBLIC_TEMPLATE:${template.key}`);
  }
  return templates;
}
